using System.Globalization;
using System.Text;

namespace LupaFiscal.Core.Evaluation;

/// <summary>Renders docs/eval/report.md from the eval history. The report is generated; edit the history or rerun eval and bench instead.</summary>
public static class EvalReport
{
    private static readonly string[] Modes = ["keyword", "vector", "hybrid"];

    public static void Write(string path, EvalHistory history) =>
        EvalHistory.WriteAtomic(path, new UTF8Encoding(false).GetBytes(Render(history)));

    public static string Render(EvalHistory history)
    {
        var md = new StringBuilder();
        md.AppendLine("# Retrieval evaluation");
        md.AppendLine();
        md.AppendLine("Generated by the `eval` and `bench` commands from `history.json` in this folder; do not edit by hand. How the questions were built: [eval/README.md](../../eval/README.md).");
        md.AppendLine();

        if (history.QuestionsHash is not null)
        {
            md.AppendLine($"- Question set: `{history.QuestionsPath}`, {history.QuestionCount} questions, {history.ExpectedCount} expected rulings, frozen hash `{history.QuestionsHash[..16]}`.");
        }
        md.AppendLine("- recall@10: share of questions with at least one expected ruling among the first 10 distinct rulings returned. The expected rulings of a question are alternative answers, so one is enough.");
        md.AppendLine("- MRR@10: mean of 1 / rank of the first expected ruling within the first 10 (0 when none).");
        md.AppendLine("- coverage@10: share of a question's expected rulings found in the first 10, out of at most 10, averaged.");
        md.AppendLine("- Ruling level: several passages of one ruling count once, at the first position. Tied scores keep the searcher's order, which is what a user sees.");
        md.AppendLine("- Modes: keyword is FTS5 BM25 only, vector is cosine similarity only, hybrid fuses both with reciprocal rank fusion. No filters.");
        if (history.TargetRecallAt10 is { } target)
        {
            md.AppendLine($"- Target: hybrid recall@10 >= {Number(target)}.");
        }
        md.AppendLine();

        var current = history.Iterations.FirstOrDefault(i => i.Config == history.LatestConfig);
        if (current is not null)
        {
            md.AppendLine("## Latest run");
            md.AppendLine();
            md.AppendLine($"{current.Label}, recorded {current.RecordedAt.ToString("yyyy-MM-dd HH:mm 'UTC'", CultureInfo.InvariantCulture)}.");
            md.AppendLine();
            md.AppendLine($"Configuration: {current.Config}");
            md.AppendLine();
            md.AppendLine("| Mode | recall@10 | MRR@10 | coverage@10 | Answered |");
            md.AppendLine("|---|---|---|---|---|");
            foreach (var mode in Modes)
            {
                if (!current.Modes.TryGetValue(mode, out var s)) continue;
                md.AppendLine($"| {mode} | {Number(s.RecallAt10)} | {Number(s.MrrAt10)} | {Number(s.CoverageAt10)} | {s.Answered} of {s.Questions} |");
            }
            if (history.TargetRecallAt10 is { } goal && current.Modes.TryGetValue("hybrid", out var hybrid))
            {
                md.AppendLine();
                md.AppendLine(hybrid.RecallAt10 >= goal
                    ? $"Hybrid recall@10 {Number(hybrid.RecallAt10)} meets the target of {Number(goal)}."
                    : $"Hybrid recall@10 {Number(hybrid.RecallAt10)} is below the target of {Number(goal)}.");
            }
            md.AppendLine();
        }

        if (history.Iterations.Count > 0)
        {
            md.AppendLine("## Iterations");
            md.AppendLine();
            md.AppendLine("Each iteration changes retrieval parameters only; the questions and expected rulings stay frozen.");
            md.AppendLine();
            md.AppendLine("| # | Label | Recorded | keyword recall@10 | keyword MRR | vector recall@10 | vector MRR | hybrid recall@10 | hybrid MRR |");
            md.AppendLine("|---|---|---|---|---|---|---|---|---|");
            for (var i = 0; i < history.Iterations.Count; i++)
            {
                var it = history.Iterations[i];
                var cells = Modes.SelectMany(m => it.Modes.TryGetValue(m, out var s)
                    ? new[] { Number(s.RecallAt10), Number(s.MrrAt10) }
                    : ["", ""]);
                md.AppendLine($"| {i} | {it.Label} | {it.RecordedAt.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)} | {string.Join(" | ", cells)} |");
            }
            md.AppendLine();
            for (var i = 0; i < history.Iterations.Count; i++)
            {
                var it = history.Iterations[i];
                md.AppendLine($"{i}. {it.Label}: {it.Config}{(it.Note is { Length: > 0 } note ? $". Change: {note}" : "")}");
            }
            md.AppendLine();
        }

        md.AppendLine("## Latency");
        md.AppendLine();
        if (history.Bench is { } bench)
        {
            md.AppendLine($"Hybrid search over the {bench.Queries} questions, query embedding included, after one warm-up query; recorded {bench.RecordedAt.ToString("yyyy-MM-dd HH:mm 'UTC'", CultureInfo.InvariantCulture)} on this machine (CPU).");
            md.AppendLine();
            md.AppendLine("| p50 | p95 | max | mean | limit | warm-up | model and vectors load |");
            md.AppendLine("|---|---|---|---|---|---|---|");
            md.AppendLine($"| {Ms(bench.P50Ms)} | {Ms(bench.P95Ms)} | {Ms(bench.MaxMs)} | {Ms(bench.MeanMs)} | {Ms(bench.LimitMs)} | {Ms(bench.WarmupMs)} | {Ms(bench.LoadMs)} |");
            md.AppendLine();
            md.AppendLine($"Configuration: {bench.Config}");
        }
        else
        {
            md.AppendLine("Not measured yet. Run: `bench --questions eval/questions.json`.");
        }
        md.AppendLine();

        if (history.Latest.Count > 0)
        {
            var failed = history.Latest.Where(q => !Within(q, "hybrid", RetrievalEvaluator.K)).ToList();
            md.AppendLine("## Failed questions (hybrid)");
            md.AppendLine();
            if (failed.Count == 0)
            {
                md.AppendLine("None: every question has an expected ruling in the hybrid top 10.");
            }
            else
            {
                md.AppendLine($"{failed.Count} question(s) with no expected ruling in the hybrid top 10. Ranks are of the first expected ruling within the top {RetrievalEvaluator.Depth} (- when absent).");
                md.AppendLine();
                md.AppendLine("| Id | Article | Question | Expected (first 3) | keyword | vector | hybrid | Hybrid top 3 |");
                md.AppendLine("|---|---|---|---|---|---|---|---|");
                foreach (var q in failed)
                {
                    md.AppendLine($"| {q.Id} | {q.Article} | {Cell(q.Question)} | {string.Join(", ", q.Expected.Take(3))}{(q.Expected.Count > 3 ? $" (+{q.Expected.Count - 3})" : "")} | " +
                        $"{Rank(q, "keyword")} | {Rank(q, "vector")} | {Rank(q, "hybrid")} | {string.Join(", ", q.HybridTop)} |");
                }
            }
            md.AppendLine();

            md.AppendLine("## Per-question ranks");
            md.AppendLine();
            md.AppendLine($"Rank of the first expected ruling within the top {RetrievalEvaluator.Depth} (- when absent).");
            md.AppendLine();
            md.AppendLine("| Id | Article | Expected | keyword | vector | hybrid |");
            md.AppendLine("|---|---|---|---|---|---|");
            foreach (var q in history.Latest)
            {
                md.AppendLine($"| {q.Id} | {q.Article} | {q.Expected.Count} | {Rank(q, "keyword")} | {Rank(q, "vector")} | {Rank(q, "hybrid")} |");
            }
        }
        return md.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    private static bool Within(QuestionRecord q, string mode, int k) =>
        q.FirstExpectedRank.TryGetValue(mode, out var rank) && rank is { } r && r <= k;

    private static string Rank(QuestionRecord q, string mode) =>
        q.FirstExpectedRank.TryGetValue(mode, out var rank) && rank is { } r ? r.ToString(CultureInfo.InvariantCulture) : "-";

    private static string Number(double value) => value.ToString("0.000", CultureInfo.InvariantCulture);

    private static string Ms(double value) => value.ToString("0", CultureInfo.InvariantCulture) + " ms";

    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal).Replace('\n', ' ');
}
